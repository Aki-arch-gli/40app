def weekly_comment(
    age,
    disease,
    calorie
):

    comment = f"""
🌱 1週間の健康評価


🥩 タンパク質

年齢とともに筋肉量が減りやすくなります。

魚・肉・卵・豆腐・乳製品などを
毎日の食事に取り入れましょう。


🥬 野菜について

野菜を毎食取り入れることで、
体調管理や便通改善につながります。

色の違う野菜を組み合わせると
よりバランスが良くなります。


🐟 魚・肉のバランス

魚と肉をバランスよく食べることで、
健康な体づくりをサポートできます。


💧 水分アドバイス

高齢になると喉の渇きを感じにくくなるため、
こまめな水分補給を心掛けましょう。

朝起きた時、
食事の時、
入浴前後がおすすめです。
"""


    if age >= 75:

        comment += """

🚶 75歳以上の方へ

食事だけでなく、
毎日の軽い運動も大切です。

無理のない範囲で、
散歩や体操を続けましょう。
"""


    if disease == "高血圧":

        comment += """

🧂 高血圧への注意

味付けは薄めを意識し、
汁物は飲みすぎないようにしましょう。
"""


    elif disease == "糖尿病":

        comment += """

🍚 糖尿病への注意

食事時間を整え、
野菜やたんぱく質から食べることもおすすめです。
"""


    elif disease == "腎臓病":

        comment += """

🫘 腎臓病への注意

医師や管理栄養士の指示を優先しながら、
無理なく食事管理を続けましょう。
"""


    elif disease == "脂質異常症":

        comment += """

🐟 脂質異常症への注意

魚や野菜を取り入れ、
脂質の摂りすぎに注意しましょう。
"""


    comment += """

🌸 最後に

毎日の食事を楽しみながら、
無理なく健康習慣を続けていきましょう😊
"""


    return comment