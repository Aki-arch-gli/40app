def normalize_food(food):

    """
    食材を比較しやすい形に変換
    """

    food = str(food).strip()

    return CATEGORY_MAP.get(
        food,
        food
    )



# ==========================
# メイン処理
# ==========================

def get_ingredients(menu):


    foods=[]


    items=menu.split("・")


    for item in items:


        item=item.strip()


        if item in BASE_INGREDIENTS:


            foods.extend(
                BASE_INGREDIENTS[item]
            )


        else:

            foods.append(item)



    # 重複削除

    foods=list(set(foods))


    # カテゴリ化

    foods=[
        normalize_food(f)
        for f in foods
    ]


    return list(set(foods))